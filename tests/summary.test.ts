import { describe, it, expect } from "vitest";
import { buildReviewSummary } from "@/lib/analysis/summary";
import { ValidatedAnalysis } from "@/lib/analysis/schema";

describe("buildReviewSummary", () => {
  const sampleAnalysis: ValidatedAnalysis = {
    concerns: [
      {
        id: "c-1",
        category: "refundable_deposit",
        observation: "Text specifies a ₹4,500 security deposit.",
        interpretation:
          "Internships rarely require interns to pay upfront equipment security fees.",
        quote: "refundable equipment deposit of ₹4,500",
        span: { start: 100, end: 139 },
      },
    ],
    missingInfo: [
      {
        id: "m-1",
        topic: "stipend_or_pay",
        note: "Stipend disbursement schedule is not stated in the provided text.",
      },
    ],
    verificationQuestions: [
      {
        id: "q-1",
        question: "Can you confirm in writing why an equipment deposit is required?",
        relatedConcernId: "c-1",
      },
    ],
    overallNote: "Review is limited to the provided communication.",
    droppedCount: 1,
    limits: [
      "Reviews supplied text only.",
      "Cannot verify identity of the sender.",
    ],
  };

  it("contains the disclaimer and title", () => {
    const summary = buildReviewSummary(sampleAnalysis);
    expect(summary).toContain("OfferCheck Review Summary");
    expect(summary).toContain(
      "Generated by OfferCheck from pasted text. Not a safety assessment."
    );
  });

  it("contains quotes copied exactly character-for-character", () => {
    const summary = buildReviewSummary(sampleAnalysis);
    expect(summary).toContain('"refundable equipment deposit of ₹4,500"');
    expect(summary).toContain("Text specifies a ₹4,500 security deposit.");
    expect(summary).toContain("Refundable Deposit Requested");
  });

  it("contains missing information and verification questions", () => {
    const summary = buildReviewSummary(sampleAnalysis);
    expect(summary).toContain("Stipend or salary");
    expect(summary).toContain(
      "Stipend disbursement schedule is not stated in the provided text."
    );
    expect(summary).toContain(
      "1. Can you confirm in writing why an equipment deposit is required?"
    );
  });

  it("contains limits and note on dropped unverified items", () => {
    const summary = buildReviewSummary(sampleAnalysis);
    expect(summary).toContain("- Reviews supplied text only.");
    expect(summary).toContain("- Cannot verify identity of the sender.");
    expect(summary).toContain(
      "1 item(s) were removed because their supporting quotes could not be matched"
    );
  });

  it("contains NO model names, attempt logs, or verdict words", () => {
    const summary = buildReviewSummary(sampleAnalysis);
    expect(summary.toLowerCase()).not.toContain("gemini");
    expect(summary.toLowerCase()).not.toContain("flash");
    expect(summary.toLowerCase()).not.toContain("attempt");
    expect(summary.toLowerCase()).not.toContain("verdict");
    expect(summary.toLowerCase()).not.toContain("verified safe");
    expect(summary.toLowerCase()).not.toContain("guaranteed safe");
    expect(summary.toLowerCase()).not.toContain("definitely a scam");
    expect(summary.toLowerCase()).not.toContain("definitely fraud");
  });

  it("contains self-checks and selected official resources with conditional reason lines", () => {
    const summary = buildReviewSummary(
      sampleAnalysis,
      "Offered through AICTE scheme and verified on NCS."
    );
    expect(summary).toContain("--- CHECK THESE YOURSELF ---");
    expect(summary).toContain("Pause before paying anything and confirm independently first.");
    expect(summary).toContain("--- OFFICIAL RESOURCES ---");
    expect(summary).toContain("If you have already paid or shared documents");
    expect(summary).toContain("1930");
    expect(summary).toContain("AICTE National Internship Portal");
    expect(summary).toContain('Shown because your text mentions "AICTE".');
    expect(summary).toContain("National Career Service");
    expect(summary).toContain('Shown because your text mentions "NCS".');
    expect(summary).toContain("Check a company's registration");
  });

  it("handles zero concerns calmly without declaring safety", () => {
    const zeroConcernAnalysis: ValidatedAnalysis = {
      concerns: [],
      missingInfo: [
        {
          id: "m-1",
          topic: "responsibilities",
          note: "Job duties are not described in detail.",
        },
      ],
      verificationQuestions: [
        {
          id: "q-1",
          question: "Can you provide a detailed job description?",
        },
      ],
      droppedCount: 0,
      limits: ["Reviews supplied text only."],
    };

    const summary = buildReviewSummary(zeroConcernAnalysis);
    expect(summary).toContain(
      "No specific concerns were identified in the text provided. This is not a safety assessment."
    );
    expect(summary.toLowerCase()).not.toContain("verified safe");
    expect(summary.toLowerCase()).not.toContain("legitimate");
  });

  it("includes company name and role title when entities are present", () => {
    const analysisWithEntities: ValidatedAnalysis = {
      ...sampleAnalysis,
      entities: {
        companyName: "AetherFlume Cloud Technologies Pvt. Ltd.",
        roleTitle: "Cloud Engineering Internship",
      },
    };
    const summary = buildReviewSummary(analysisWithEntities);
    expect(summary).toContain(
      "Company name: AetherFlume Cloud Technologies Pvt. Ltd."
    );
    expect(summary).toContain("Role title: Cloud Engineering Internship");
  });
});
